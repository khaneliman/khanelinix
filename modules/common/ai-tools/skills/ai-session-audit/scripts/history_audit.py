class HistoryError(Exception):
    """Invalid input or unusable archive."""


# --- Shared helpers --------------------------------------------------------


def connect(path: Path) -> sqlite3.Connection:
    if not path.is_file():
        raise HistoryError(f"archive not found: {path}")
    db = sqlite3.connect(f"{path.resolve().as_uri()}?mode=ro", uri=True)
    db.row_factory = sqlite3.Row
    return db


def table_columns(db: sqlite3.Connection, table: str) -> set[str]:
    return {row[1] for row in db.execute(f"pragma table_info({table})")}


def column(columns: set[str], name: str, fallback: str) -> str:
    return name if name in columns else fallback


def relationship_expression(db: sqlite3.Connection, alias: str = "s") -> str:
    if "relationship_type" in table_columns(db, "sessions"):
        return f"coalesce({alias}.relationship_type,'')"
    return "''"


def installed_pattern(roots: Sequence[str]) -> re.Pattern[str]:
    return re.compile("(?:" + "|".join(roots) + r")/([A-Za-z0-9._-]+)/SKILL\.md")


def explicit_names(text: str, aliases: dict[str, str]) -> Iterable[str]:
    for match in EXPLICIT_SKILL.finditer(text):
        name = (match.group(2) or match.group(1)).lower()
        yield aliases.get(name, name)


def redact(text: str) -> str:
    return SECRET.sub("<redacted-secret>", text)


def day(value: Any) -> str:
    return str(value or "")[:10]


def window_label(value: str, boundaries: Sequence[str]) -> str:
    previous = None
    for boundary in boundaries:
        if value < boundary:
            return f"<{boundary}" if previous is None else f"{previous}..{boundary}"
        previous = boundary
    return f">={previous}" if previous is not None else "all"


def secure_dir(path: Path) -> None:
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(path, 0o700)


def write_text(path: Path, text: str, force: bool) -> Path:
    if path.exists() and not force:
        raise HistoryError(f"{path} exists; pass --force to replace it")
    secure_dir(path.parent)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.chmod(path, 0o600)
    return path


def write_json(path: Path, value: Any, force: bool) -> Path:
    return write_text(
        path, json.dumps(value, indent=1, ensure_ascii=False) + "\n", force
    )


def write_jsonl(path: Path, rows: Iterable[dict[str, Any]], force: bool) -> Path:
    return write_text(
        path, "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), force
    )


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        raise HistoryError(f"missing input {path}; run the extract command first")
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def markdown_table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend(
        "| " + " | ".join(str(cell).replace("|", "\\|") for cell in row) + " |"
        for row in rows
    )
    return "\n".join(lines) + "\n"


# --- status ----------------------------------------------------------------


def status(db: sqlite3.Connection, now: dt.datetime | None = None) -> dict[str, Any]:
    columns = table_columns(db, "sessions")
    relationship = column(columns, "relationship_type", "''")
    rows = db.execute(
        f"""select agent, count(*) sessions, max(started_at) newest,
        sum(case when coalesce({relationship},'')<>'' then 1 else 0 end) subagents
        from sessions group by agent order by sessions desc"""
    ).fetchall()
    agents = [dict(row) for row in rows]
    newest = max((row["newest"] or "" for row in agents), default="")
    now = now or dt.datetime.now(dt.timezone.utc)
    stale_days = None
    if newest:
        parsed = dt.datetime.fromisoformat(newest[:19]).replace(tzinfo=dt.timezone.utc)
        stale_days = round((now - parsed).total_seconds() / 86400, 1)
    return {"agents": agents, "newest_session": newest, "stale_days": stale_days}


# --- extract ---------------------------------------------------------------


def clean(text: str) -> tuple[str | None, dict[str, Any]]:
    meta: dict[str, Any] = {
        "images": 0,
        "slash": None,
        "template": None,
        "dropped": None,
    }
    if not text:
        return None, meta
    raw = text
    for name, pattern in TEMPLATES.items():
        if pattern.search(raw):
            meta["template"] = name
            break
    if meta["template"] == "codex-review-action":
        return "<codex /review action>", meta
    if meta["template"] == "plan-implement":
        # The plan body is agent-authored; keep only the UI action marker.
        return "<plan-implement action>", meta
    command = COMMAND_NAME.search(raw)
    if command:
        arguments = COMMAND_ARGS.search(raw)
        meta["slash"] = command.group(1)
        return (
            f"{command.group(1)} {arguments.group(1).strip() if arguments else ''}".strip(),
            meta,
        )
    meta["images"] = len(re.findall(r"<image name=", raw)) + len(
        IMAGE_TOKEN.findall(raw)
    )
    text = CODEX_REQUEST.sub("", text)
    for block in WRAPPER_BLOCKS:
        text = block.sub("", text)
    text = OPENCODE_MODE.sub("", text)
    text = OPENCODE_INLINED.sub("", text)
    text = IMAGE_TOKEN.sub("", text).strip()
    if not text:
        return ("<image-only>" if meta["images"] else None), meta
    if any(pattern.search(text) for pattern in INJECTED):
        meta["dropped"] = "injected"
        return None, meta
    if AGENT_RELAYED.search(text) or PATH_ONLY.match(text):
        meta["dropped"] = "agent-relayed"
        return None, meta
    if text[0] in "/$":
        meta["slash"] = text.split()[0]
    return text, meta


def prompt_tags(text: str) -> list[str]:
    tags = []
    if GITHUB_PR.search(text):
        tags.append("github_pr_url")
    if PR_REVIEW.search(text):
        tags.append("pr_review")
    if REVIEW_WORD.search(text):
        tags.append("review_any")
    if EXPLICIT_SKILL.search(text):
        tags.append("explicit_skill")
    return tags


def load_sessions(
    db: sqlite3.Connection, agents: Sequence[str]
) -> dict[str, dict[str, Any]]:
    columns = table_columns(db, "sessions")
    fields = {
        "project": column(columns, "project", "''"),
        "cwd": column(columns, "cwd", "''"),
        "entrypoint": column(columns, "entrypoint", "''"),
        "relationship": f"coalesce({column(columns, 'relationship_type', 'NULL')},'')",
        "automated": f"coalesce({column(columns, 'is_automated', '0')},0)",
    }
    select = ", ".join(f"{expression} AS {name}" for name, expression in fields.items())
    placeholders = ",".join("?" * len(agents))
    rows = db.execute(
        f"select id, agent, started_at, {select} from sessions where agent in ({placeholders})",
        list(agents),
    )
    return {row["id"]: dict(row) for row in rows}


def extract(
    db: sqlite3.Connection, agents: Sequence[str], since: str, until: str
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    sessions = {
        sid: sess
        for sid, sess in load_sessions(db, agents).items()
        if since <= day(sess["started_at"]) < until
    }
    columns = table_columns(db, "messages")
    system = column(columns, "is_system", "0")
    timestamp = column(columns, "timestamp", "NULL")
    dropped: collections.Counter[str] = collections.Counter()
    prompts: list[dict[str, Any]] = []
    first_prompt: dict[str, str] = {}
    for row in db.execute(
        f"""select session_id, ordinal, {timestamp} AS ts, content from messages
        where role='user' and coalesce({system},0)=0 order by session_id, ordinal"""
    ):
        sess = sessions.get(row["session_id"])
        if sess is None:
            continue
        if sess["relationship"]:
            dropped["subagent-session"] += 1
            continue
        if sess["automated"]:
            dropped["automated-session"] += 1
            continue
        text, meta = clean(row["content"] or "")
        if text is None:
            dropped[meta["dropped"] or "empty"] += 1
            continue
        first_prompt.setdefault(row["session_id"], text)
        prompts.append(
            {
                "session_id": row["session_id"],
                "agent": sess["agent"],
                "project": sess["project"],
                "session_started": sess["started_at"],
                "ts": row["ts"] or sess["started_at"],
                "ordinal": row["ordinal"],
                "text": redact(text),
                "images": meta["images"],
                "slash": meta["slash"],
                "template": meta["template"],
                "tags": prompt_tags(text),
            }
        )
    probes = {
        sid
        for sid, text in first_prompt.items()
        if any(p.search(text) for p in PROBE_FIRST)
    }
    kept = [prompt for prompt in prompts if prompt["session_id"] not in probes]
    dropped["probe-session"] = len(prompts) - len(kept)
    by_session: dict[str, list[dict[str, Any]]] = collections.defaultdict(list)
    for prompt in kept:
        by_session[prompt["session_id"]].append(prompt)
    for items in by_session.values():
        for index, prompt in enumerate(items):
            prompt["turn"] = index
            prompt["turns_in_session"] = len(items)
    session_rows = [
        {**sessions[sid], "id": sid, "human_turns": len(items)}
        for sid, items in sorted(by_session.items())
    ]
    summary = {
        "sessions": len(by_session),
        "prompts": len(kept),
        "dropped": dict(sorted(dropped.items())),
        "by_agent": dict(collections.Counter(p["agent"] for p in kept).most_common()),
        "by_agent_month": dict(
            sorted(
                collections.Counter(
                    f"{p['agent']} {day(p['ts'])[:7]}" for p in kept
                ).items()
            )
        ),
    }
    return kept, session_rows, summary


# --- threads and digests ---------------------------------------------------


def is_review_session(prompts: Sequence[dict[str, Any]]) -> bool:
    for prompt in prompts:
        tags = set(prompt["tags"])
        if "pr_review" in tags or prompt.get("template") == "codex-review-action":
            return True
        if "github_pr_url" in tags and "review_any" in tags:
            return True
        if (
            prompt.get("slash")
            and REVIEW_COMMAND.match(prompt["slash"])
            and tags & {"github_pr_url", "review_any"}
        ):
            return True
    return False


def build_threads(
    db: sqlite3.Connection,
    prompts: Sequence[dict[str, Any]],
    sessions: Sequence[dict[str, Any]],
    select: str,
    prompt_chars: int,
    reply_chars: int,
) -> list[dict[str, Any]]:
    by_session: dict[str, list[dict[str, Any]]] = collections.defaultdict(list)
    for prompt in prompts:
        by_session[prompt["session_id"]].append(prompt)
    meta = {sess["id"]: sess for sess in sessions}
    skills = observed_skills(db, {}, installed_pattern(DEFAULT_INSTALLED_ROOTS))
    tool_use = column(table_columns(db, "messages"), "has_tool_use", "0")
    records = []
    for sid, items in sorted(by_session.items(), key=lambda kv: kv[1][0]["ts"] or ""):
        if select == "review" and not is_review_session(items):
            continue
        ordinals = [p["ordinal"] for p in items]
        replies = db.execute(
            f"""select ordinal, content, coalesce({tool_use},0) tool from messages
            where session_id=? and role='assistant' order by ordinal""",
            (sid,),
        ).fetchall()
        turns = []
        for index, prompt in enumerate(items):
            end = ordinals[index + 1] if index + 1 < len(ordinals) else float("inf")
            window = [
                r
                for r in replies
                if prompt["ordinal"] < r["ordinal"] < end
                and (r["content"] or "").strip()
            ]
            # Prefer the last prose reply over a trailing tool-call rendering.
            prose = [r for r in window if not r["tool"]] or window
            turns.append(
                {
                    "turn": index,
                    "ts": prompt["ts"],
                    "user": prompt["text"][:prompt_chars],
                    "assistant_final": redact(
                        (prose[-1]["content"] if prose else "")[:reply_chars]
                    ),
                }
            )
        sess = meta.get(sid, {})
        records.append(
            {
                "session_id": sid,
                "agent": items[0]["agent"],
                "project": sess.get("project"),
                "started_at": sess.get("started_at") or items[0]["ts"],
                "skills_loaded": sorted(skills.get(sid, {})),
                "human_turns": len(items),
                "turns": turns,
            }
        )
    return records


def render_chunks(blocks: Iterable[str], chunk_bytes: int) -> list[str]:
    chunks: list[list[str]] = [[]]
    size = 0
    for block in blocks:
        encoded = len(block.encode("utf-8"))
        if size + encoded > chunk_bytes and chunks[-1]:
            chunks.append([])
            size = 0
        chunks[-1].append(block)
        size += encoded
    return ["".join(chunk) for chunk in chunks if chunk]


def digest_blocks(
    threads: Sequence[dict[str, Any]],
    since: str,
    until: str,
    agents: set[str],
    min_turns: int,
    max_turns: int,
    cap_turns: int,
    user_chars: int,
    reply_chars: int,
) -> list[str]:
    blocks = []
    count = 0
    for record in threads:
        started = day(record["started_at"])
        if record["agent"] not in agents or not (since <= started < until):
            continue
        if not (min_turns <= record["human_turns"] <= max_turns):
            continue
        count += 1
        lines = [
            (
                f"\n## S{count} | {record['agent']} | {started} | {record['project']} | "
                f"skills: {','.join(record['skills_loaded']) or '-'} | turns: {record['human_turns']}"
            )
        ]
        for turn in record["turns"][:cap_turns]:
            lines.append(
                f"T{turn['turn']} USER: {' '.join(turn['user'][:user_chars].split())}"
            )
            reply = " ".join(turn["assistant_final"][:reply_chars].split())
            if reply:
                lines.append(f"T{turn['turn']} AGENT: {reply}")
        blocks.append("\n".join(lines) + "\n")
    return blocks


def correction_blocks(
    threads: Sequence[dict[str, Any]],
    review_ids: set[str],
    since: str,
    until: str,
    agents: set[str],
    include_review: bool,
    min_turns: int,
    max_turns: int,
    max_user_chars: int,
    reply_chars: int,
) -> tuple[list[str], int]:
    blocks = []
    selected = 0
    for record in threads:
        started = day(record["started_at"])
        if record["agent"] not in agents or not (since <= started < until):
            continue
        if record["session_id"] in review_ids and not include_review:
            continue
        if not (min_turns <= record["human_turns"] <= max_turns):
            continue
        turns = record["turns"]
        picked = [
            (turn["turn"], turns[index - 1]["assistant_final"], turn["user"])
            for index, turn in enumerate(turns)
            if index > 0
            and len(turn["user"]) <= max_user_chars
            and STRONG_CORRECTION.search(turn["user"])
        ]
        if not picked:
            continue
        first = " ".join(turns[0]["user"][:220].split())
        lines = [
            f"\n## {record['agent']} | {started} | {record['project']} | first: {first}"
        ]
        for number, previous, text in picked:
            lines.append(
                f"  AGENT(prev, tail): {' '.join(previous[-reply_chars:].split())}"
            )
            lines.append(f"  USER T{number}: {' '.join(text.split())}")
        selected += len(picked)
        blocks.append("\n".join(lines) + "\n")
    return blocks, selected


def write_chunks(
    out: Path, prefix: str, chunks: Sequence[str], force: bool
) -> list[str]:
    paths = []
    for index, chunk in enumerate(chunks, 1):
        paths.append(
            str(write_text(out / "digests" / f"{prefix}-{index}.md", chunk, force))
        )
    return paths


