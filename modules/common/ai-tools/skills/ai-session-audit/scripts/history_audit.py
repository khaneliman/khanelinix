def blame_lines(file: Path, repo: Path) -> list[tuple[str, str]]:
    try:
        relative = file.resolve().relative_to(repo)
    except ValueError as error:
        raise HistoryError(
            f"{file} resolves outside {repo}; pass the repository source file"
        ) from error
    result = subprocess.run(
        ["git", "-C", str(repo), "blame", "--line-porcelain", "--", str(relative)],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise HistoryError(f"git blame failed for {file}: {result.stderr.strip()}")
    lines: list[tuple[str, str]] = []
    sha = ""
    for line in result.stdout.splitlines():
        if line.startswith("\t"):
            lines.append((sha, line[1:]))
        elif re.match(r"^[0-9a-f]{40} ", line):
            sha = line.split()[0]
    return lines


def commit_info(repo: Path, shas: Iterable[str]) -> dict[str, dict[str, str]]:
    real = sorted({sha for sha in shas if sha.strip("0")})
    info: dict[str, dict[str, str]] = {}
    if real:
        result = subprocess.run(
            [
                "git",
                "-C",
                str(repo),
                "show",
                "-s",
                "--date=short",
                "--format=%H%x1f%ad%x1f%s%x1f%b%x1e",
                *real,
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0:
            raise HistoryError(f"git show failed: {result.stderr.strip()}")
        for record in result.stdout.split("\x1e"):
            parts = record.strip("\n").split("\x1f")
            if len(parts) == 4:
                why = next(
                    (line.strip() for line in parts[3].splitlines() if line.strip()), ""
                )
                info[parts[0]] = {"date": parts[1], "subject": parts[2], "why": why}
    return info


def rule_blocks(lines: Sequence[tuple[str, str]]) -> list[dict[str, Any]]:
    blocks: list[dict[str, Any]] = []
    current: dict[str, Any] | None = None
    fenced = False
    for number, (sha, text) in enumerate(lines, 1):
        stripped = text.strip()
        if not stripped and not fenced:
            current = None
            continue
        # Headings and list items open blocks; other lines continue one.
        starts = not fenced and bool(
            stripped.startswith("#") or re.match(r"^([-*]|\d+\.)\s", text)
        )
        if current is None or starts:
            current = {"start": number, "end": number, "lines": [], "shas": []}
            blocks.append(current)
        current["end"] = number
        current["lines"].append(text)
        current["shas"].append(sha)
        if stripped.startswith("```"):
            fenced = not fenced
        if stripped.startswith("#") and not fenced:
            current = None
    return blocks


def ledger(file: Path, repo: Path | None) -> dict[str, Any]:
    if not file.is_file():
        raise HistoryError(f"instruction file not found: {file}")
    if repo is None:
        top = subprocess.run(
            ["git", "-C", str(file.resolve().parent), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=False,
        )
        if top.returncode != 0:
            raise HistoryError(f"{file} is not inside a git repository")
        repo = Path(top.stdout.strip())
    lines = blame_lines(file, repo.resolve())
    info = commit_info(repo, (sha for sha, _ in lines))
    result = []
    for block in rule_blocks(lines):
        commits = []
        for sha in dict.fromkeys(block["shas"]):
            meta = info.get(sha)
            commits.append(
                {"sha": sha[:9], **meta}
                if meta
                else {"sha": "uncommitted", "date": "", "subject": "", "why": ""}
            )
        commits.sort(key=lambda item: item["date"])
        dated = [item["date"] for item in commits if item["date"]]
        result.append(
            {
                "lines": f"{block['start']}-{block['end']}",
                "text": " ".join(" ".join(block["lines"]).split())[:160],
                "first_added": min(dated) if dated else "",
                "last_changed": max(dated) if dated else "",
                "commits": commits,
            }
        )
    return {"file": str(file), "blocks": result}


def ledger_markdown(report: dict[str, Any]) -> str:
    text = f"# Rule ledger: {report['file']}\n\n"
    return text + markdown_table(
        ("lines", "added", "changed", "latest commit", "text"),
        (
            (
                block["lines"],
                block["first_added"],
                block["last_changed"],
                (block["commits"][-1]["sha"] + " " + block["commits"][-1]["subject"])
                if block["commits"]
                else "",
                block["text"],
            )
            for block in report["blocks"]
        ),
    )


