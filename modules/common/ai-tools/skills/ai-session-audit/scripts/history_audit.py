def add_scope(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--since", default="", help="first session date to include (YYYY-MM-DD)"
    )
    parser.add_argument(
        "--until",
        default="9999-12-31",
        help="first session date to exclude (YYYY-MM-DD)",
    )
    parser.add_argument(
        "--agents",
        default=",".join(DEFAULT_AGENTS),
        help="comma-separated archive agents",
    )


def add_output(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--out", type=Path, required=True, help="run directory for derived artifacts"
    )
    parser.add_argument(
        "--force", action="store_true", help="replace existing artifacts"
    )


def add_boundaries(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--boundary",
        action="append",
        default=[],
        help="policy change date splitting comparison windows; repeatable",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=DESCRIPTION)
    sub = parser.add_subparsers(dest="command", required=True)
    for name, text in (
        ("status", "report archive coverage and staleness"),
        ("extract", "write cleaned human prompts and session metadata"),
        ("threads", "write turn-level transcripts from extracted prompts"),
        ("digest", "render review threads as chunked worker digests"),
        ("corrections", "render follow-up correction turns as chunked digests"),
        ("routing", "compare expected and observed skill loads"),
        ("phrases", "rank phrases repeated across sessions"),
        ("signals", "count stall, commit, review, and harness-error signals"),
        ("ledger", "trace git provenance for each rule block in an instruction file"),
        ("run", "run status, extract, threads, routing, phrases, signals, and digests"),
    ):
        child = sub.add_parser(name, help=text)
        if name != "ledger":
            child.add_argument(
                "--db", type=Path, default=DEFAULT_DB, help="AgentsView sessions.db"
            )
        if name in {"extract", "run", "digest", "corrections"}:
            add_scope(child)
        if name != "status":
            add_output(child)
        if name in {"routing", "signals", "run"}:
            add_boundaries(child)
        if name in {"routing", "run"}:
            child.add_argument("--triggers", type=Path, default=DEFAULT_TRIGGERS)
            child.add_argument(
                "--skills-root",
                type=Path,
                help="git checkout of canonical skills for creation dates",
            )
        if name in {"threads", "run"}:
            child.add_argument("--prompt-chars", type=int, default=1600)
            child.add_argument("--reply-chars", type=int, default=1200)
        if name in {"digest", "corrections", "run"}:
            child.add_argument("--chunk-bytes", type=int, default=420_000)
            child.add_argument("--min-session-turns", type=int, default=2)
            child.add_argument("--max-session-turns", type=int, default=45)
        if name == "digest":
            child.add_argument("--threads", default="threads-review.jsonl")
            child.add_argument("--prefix", default="review")
            child.add_argument("--cap-turns", type=int, default=45)
        if name == "corrections":
            child.add_argument("--prefix", default="corrections")
            child.add_argument("--include-review", action="store_true")
        if name == "phrases":
            child.add_argument("--min-sessions", type=int, default=6)
            child.add_argument("--limit", type=int, default=150)
        if name == "ledger":
            child.add_argument(
                "--file",
                type=Path,
                required=True,
                help="instruction file, such as base.md",
            )
            child.add_argument(
                "--repo",
                type=Path,
                help="git repository root; defaults to the file's repository",
            )
    return parser


def run_threads(args: argparse.Namespace, db: sqlite3.Connection) -> dict[str, Any]:
    prompts = read_jsonl(args.out / "prompts.jsonl")
    sessions = read_jsonl(args.out / "sessions.jsonl")
    review = build_threads(
        db, prompts, sessions, "review", args.prompt_chars, args.reply_chars
    )
    everything = build_threads(
        db, prompts, sessions, "all", args.prompt_chars, args.reply_chars
    )
    write_jsonl(args.out / "threads-review.jsonl", review, args.force)
    write_jsonl(args.out / "threads-all.jsonl", everything, args.force)
    return {"review_sessions": len(review), "sessions": len(everything)}


def run_digests(
    args: argparse.Namespace, threads_name: str, prefix: str, cap_turns: int
) -> list[str]:
    threads = read_jsonl(args.out / threads_name)
    blocks = digest_blocks(
        threads,
        args.since,
        args.until,
        set(args.agents.split(",")),
        args.min_session_turns,
        args.max_session_turns,
        cap_turns,
        1200,
        700,
    )
    return write_chunks(
        args.out, prefix, render_chunks(blocks, args.chunk_bytes), args.force
    )


def run_corrections(
    args: argparse.Namespace,
    prefix: str,
    include_review: bool,
    min_turns: int,
    max_turns: int,
    reply_chars: int,
) -> dict[str, Any]:
    threads = read_jsonl(args.out / "threads-all.jsonl")
    review_ids = {
        row["session_id"] for row in read_jsonl(args.out / "threads-review.jsonl")
    }
    blocks, selected = correction_blocks(
        threads,
        review_ids,
        args.since,
        args.until,
        set(args.agents.split(",")),
        include_review,
        min_turns,
        max_turns,
        1500,
        reply_chars,
    )
    paths = write_chunks(
        args.out, prefix, render_chunks(blocks, args.chunk_bytes), args.force
    )
    return {"turns": selected, "files": paths}


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "ledger":
            report = ledger(args.file, args.repo)
            write_json(args.out / "ledger.json", report, args.force)
            write_text(args.out / "ledger.md", ledger_markdown(report), args.force)
            print(json.dumps({"blocks": len(report["blocks"]), "out": str(args.out)}))
            return 0
        db = connect(args.db)
        if args.command == "status":
            print(json.dumps(status(db), indent=1))
            return 0
        agents = getattr(args, "agents", ",".join(DEFAULT_AGENTS)).split(",")
        boundaries = sorted(getattr(args, "boundary", []) or [])
        manifest: dict[str, Any] = {}
        if args.command in {"extract", "run"}:
            if (
                args.command == "run"
                and args.out.exists()
                and any(args.out.iterdir())
                and not args.force
            ):
                raise HistoryError(
                    f"{args.out} is not empty; pass --force to replace its artifacts"
                )
            prompts, sessions, summary = extract(db, agents, args.since, args.until)
            write_jsonl(args.out / "prompts.jsonl", prompts, args.force)
            write_jsonl(args.out / "sessions.jsonl", sessions, args.force)
            write_json(args.out / "extract-summary.json", summary, args.force)
            manifest["extract"] = summary
        if args.command in {"threads", "run"}:
            manifest["threads"] = run_threads(args, db)
        if args.command in {"routing", "run"}:
            report = routing(
                db,
                read_jsonl(args.out / "prompts.jsonl"),
                load_triggers(args.triggers),
                boundaries,
                args.skills_root,
            )
            write_json(args.out / "routing.json", report, args.force)
            write_text(args.out / "routing.md", routing_markdown(report), args.force)
            manifest["routing_rows"] = len(report["rows"])
        if args.command in {"phrases", "run"}:
            report = phrases(
                read_jsonl(args.out / "prompts.jsonl"),
                getattr(args, "min_sessions", 6),
                getattr(args, "limit", 150),
            )
            write_json(args.out / "phrases.json", report, args.force)
            write_text(args.out / "phrases.md", phrases_markdown(report), args.force)
            manifest["phrases"] = len(report["phrases"])
        if args.command in {"signals", "run"}:
            report = signals(db, read_jsonl(args.out / "prompts.jsonl"), boundaries)
            write_json(args.out / "signals.json", report, args.force)
            write_text(args.out / "signals.md", signals_markdown(report), args.force)
            manifest["signals_rows"] = len(report["prompt_signals"])
        if args.command == "digest":
            manifest["digests"] = run_digests(
                args, args.threads, args.prefix, args.cap_turns
            )
        if args.command == "corrections":
            manifest["corrections"] = run_corrections(
                args,
                args.prefix,
                args.include_review,
                args.min_session_turns,
                args.max_session_turns,
                450,
            )
        if args.command == "run":
            manifest["status"] = status(db)
            manifest["review_digests"] = run_digests(
                args, "threads-review.jsonl", "review", 45
            )
            manifest["correction_digests"] = run_corrections(
                args,
                "corrections",
                False,
                args.min_session_turns,
                args.max_session_turns,
                450,
            )
            manifest["orchestration_digests"] = run_corrections(
                args, "orchestration", True, args.max_session_turns + 1, 10**9, 350
            )
            manifest["arguments"] = {
                "since": args.since,
                "until": args.until,
                "agents": agents,
                "boundaries": boundaries,
            }
            write_json(args.out / "manifest.json", manifest, args.force)
        print(json.dumps(manifest, indent=1, default=str)[:4000])
        return 0
    except HistoryError as error:
        print(f"history_audit: {error}", file=sys.stderr)
        return 2
    except (sqlite3.Error, OSError) as error:
        print(f"history_audit: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
