def load_triggers(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise HistoryError(f"invalid triggers file {path}: {error}") from error
    skills = data.get("skills")
    if not isinstance(skills, dict) or not skills:
        raise HistoryError(f"triggers file {path} needs a non-empty skills object")
    for name, spec in skills.items():
        if not isinstance(spec, dict) or not isinstance(spec.get("prompt"), str):
            raise HistoryError(f"trigger {name} needs a prompt regex")
        spec["compiled"] = re.compile(spec["prompt"], re.IGNORECASE)
    data.setdefault("aliases", {})
    data["installed"] = installed_pattern(
        data.get("installed_skill_roots") or DEFAULT_INSTALLED_ROOTS
    )
    return data


def skill_created(skills_root: Path | None, name: str) -> str | None:
    if skills_root is None:
        return None
    result = subprocess.run(
        [
            "git",
            "-C",
            str(skills_root),
            "log",
            "--diff-filter=A",
            "--format=%ad",
            "--date=short",
            "--",
            f"{name}/SKILL.md",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    dates = result.stdout.split()
    return dates[-1] if result.returncode == 0 and dates else None


def creation_dates(
    triggers: dict[str, Any], skills_root: Path | None
) -> dict[str, str | None]:
    """Earliest creation date per skill, counting renamed predecessors."""
    created: dict[str, str | None] = {}
    for name, spec in triggers["skills"].items():
        names = [
            name,
            *(old for old, new in triggers["aliases"].items() if new == name),
        ]
        dates = (
            [spec.get("since")]
            if spec.get("since")
            else [skill_created(skills_root, item) for item in names]
        )
        known = [value for value in dates if value]
        created[name] = min(known) if known else None
    return created


def observed_skills(
    db: sqlite3.Connection,
    aliases: dict[str, str],
    installed: re.Pattern[str] | None = None,
) -> dict[str, dict[str, float]]:
    """Map session -> skill -> earliest order key of load evidence."""
    columns = table_columns(db, "tool_calls")
    order = "m.ordinal" if "message_id" in columns else "t.rowid"
    join = (
        "left join messages m on m.id = t.message_id" if "message_id" in columns else ""
    )
    loads: dict[str, dict[str, float]] = collections.defaultdict(dict)

    def note(sid: str, name: str, key: Any) -> None:
        name = aliases.get(name, name)
        position = float(key) if key is not None else float("inf")
        if position < loads[sid].get(name, float("inf")):
            loads[sid][name] = position

    for row in db.execute(
        f"select t.session_id sid, t.skill_name name, {order} pos from tool_calls t {join} "
        "where coalesce(t.skill_name,'')<>''"
    ):
        note(row["sid"], row["name"], row["pos"])
    if installed is not None:
        # AgentsView's skill_name misses most Codex skill reads; count reads of
        # installed copies, not repository sources being edited.
        for row in db.execute(
            f"select t.session_id sid, t.input_json inp, {order} pos from tool_calls t {join} "
            "where t.input_json like '%SKILL.md%'"
        ):
            for name in installed.findall(row["inp"] or ""):
                note(row["sid"], name, row["pos"])
    return loads


def routing(
    db: sqlite3.Connection,
    prompts: Sequence[dict[str, Any]],
    triggers: dict[str, Any],
    boundaries: Sequence[str],
    skills_root: Path | None,
) -> dict[str, Any]:
    aliases = triggers["aliases"]
    loads = observed_skills(db, aliases, triggers["installed"])
    created = creation_dates(triggers, skills_root)
    sessions: dict[str, dict[str, Any]] = {}
    for prompt in prompts:
        # Windows follow the session start, matching extract's date filter.
        started = day(prompt.get("session_started") or prompt["ts"])
        sess = sessions.setdefault(
            prompt["session_id"],
            {
                "agent": prompt["agent"],
                "day": started,
                "expected": set(),
                "explicit": {},
            },
        )
        for name, spec in triggers["skills"].items():
            if spec["compiled"].search(prompt["text"]):
                sess["expected"].add(name)
        for name in explicit_names(prompt["text"], aliases):
            sess["explicit"].setdefault(name, prompt["ordinal"])
    table: dict[tuple[str, str, str], collections.Counter[str]] = (
        collections.defaultdict(collections.Counter)
    )
    for sid, sess in sessions.items():
        for name in sess["expected"]:
            if created.get(name) and sess["day"] < created[name]:
                continue
            counter = table[
                (sess["agent"], name, window_label(sess["day"], boundaries))
            ]
            explicit = name in sess["explicit"]
            loaded = name in loads.get(sid, {})
            counter["expected"] += 1
            counter["explicit"] += int(explicit)
            counter["auto"] += int(loaded and not explicit)
            counter["missing"] += int(not loaded and not explicit)
    rows = [
        {"agent": agent, "skill": skill, "window": window, **dict(counter)}
        for (agent, skill, window), counter in sorted(table.items())
    ]
    return {
        "created": created,
        "rows": rows,
        "edits": edit_before_load(db, prompts, triggers, loads, boundaries),
    }


def edit_before_load(
    db: sqlite3.Connection,
    prompts: Sequence[dict[str, Any]],
    triggers: dict[str, Any],
    loads: dict[str, dict[str, float]],
    boundaries: Sequence[str],
) -> list[dict[str, Any]]:
    suffixes = {
        name: tuple(spec["edit_suffixes"])
        for name, spec in triggers["skills"].items()
        if spec.get("edit_suffixes")
    }
    if not suffixes:
        return []
    columns = table_columns(db, "tool_calls")
    order = "m.ordinal" if "message_id" in columns else "t.rowid"
    join = (
        "left join messages m on m.id = t.message_id" if "message_id" in columns else ""
    )
    # sessions also has file_path; qualify it for the join.
    file_path = "t.file_path" if "file_path" in columns else "NULL"
    relationship = relationship_expression(db)
    explicit: dict[str, dict[str, float]] = collections.defaultdict(dict)
    for prompt in prompts:
        for name in explicit_names(prompt["text"], triggers["aliases"]):
            explicit[prompt["session_id"]].setdefault(name, float(prompt["ordinal"]))
    first_edit: dict[tuple[str, str], tuple[float, str, str, str]] = {}
    tools = ",".join("?" * len(EDIT_TOOLS))
    for row in db.execute(
        f"""select t.session_id sid, t.tool_name tool, {file_path} path, t.input_json inp, {order} pos,
        s.agent agent, s.started_at started, {relationship} rel
        from tool_calls t {join} join sessions s on s.id = t.session_id
        where t.tool_name in ({tools})""",
        sorted(EDIT_TOOLS),
    ):
        paths = [row["path"]] if row["path"] else PATCH_PATH.findall(row["inp"] or "")
        for name, endings in suffixes.items():
            if any(path.endswith(endings) for path in paths if path):
                key = (row["sid"], name)
                position = float(row["pos"]) if row["pos"] is not None else float("inf")
                if key not in first_edit or position < first_edit[key][0]:
                    first_edit[key] = (
                        position,
                        row["agent"],
                        day(row["started"]),
                        "subagent" if row["rel"] else "root",
                    )
    table: dict[tuple[str, str, str, str], collections.Counter[str]] = (
        collections.defaultdict(collections.Counter)
    )
    for (sid, name), (position, agent, started, kind) in first_edit.items():
        loaded_at = min(
            loads.get(sid, {}).get(name, float("inf")),
            explicit.get(sid, {}).get(name, float("inf")),
        )
        outcome = (
            "before-edit"
            if loaded_at <= position
            else ("after-edit" if loaded_at < float("inf") else "never")
        )
        table[(agent, kind, name, window_label(started, boundaries))][outcome] += 1
    return [
        {
            "agent": agent,
            "session_kind": kind,
            "skill": name,
            "window": window,
            **dict(counter),
        }
        for (agent, kind, name, window), counter in sorted(table.items())
    ]


