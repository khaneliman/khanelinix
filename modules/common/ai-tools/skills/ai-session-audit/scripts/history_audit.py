def prose_tokens(text: str) -> list[str]:
    kept = []
    for line in text.splitlines():
        letters = sum(ch.isalpha() or ch.isspace() for ch in line)
        if line.strip() and not LOGLIKE.search(line) and letters >= 0.8 * len(line):
            kept.append(line)
    lowered = "\n".join(kept).lower()
    lowered = re.sub(r"https?://\S+", " <url> ", lowered)
    lowered = re.sub(r"(?:~|/)[\w./-]{3,}", " <path> ", lowered)
    lowered = re.sub(r"\b\d+\b", " <n> ", lowered)
    return re.findall(r"<url>|<path>|<n>|[a-z$][a-z0-9'$_-]*", lowered)


def phrases(
    prompts: Sequence[dict[str, Any]], min_sessions: int, limit: int
) -> dict[str, Any]:
    grams: dict[tuple[str, ...], set[str]] = collections.defaultdict(set)
    months: dict[tuple[str, ...], set[str]] = collections.defaultdict(set)
    short: dict[str, set[str]] = collections.defaultdict(set)
    for prompt in prompts:
        if prompt.get("template"):
            continue
        tokens = prose_tokens(prompt["text"][:4000])
        normalized = " ".join(tokens)
        if 0 < len(normalized) <= 60:
            short[normalized].add(prompt["session_id"])
        seen = set()
        for size in range(3, 8):
            for start in range(len(tokens) - size + 1):
                gram = tuple(tokens[start : start + size])
                content = [
                    token
                    for token in gram
                    if token not in STOP_WORDS and not token.startswith("<")
                ]
                if len(content) < 2 or gram in seen:
                    continue
                seen.add(gram)
                grams[gram].add(prompt["session_id"])
                months[gram].add(day(prompt["ts"])[:7])
    ranked = sorted(
        ((gram, len(ids)) for gram, ids in grams.items() if len(ids) >= min_sessions),
        key=lambda item: (-len(item[0]), -item[1]),
    )
    kept: list[tuple[tuple[str, ...], int]] = []
    for gram, count in ranked:
        text = " ".join(gram)
        # Keep maximal phrases: drop a gram covered by a longer one with similar reach.
        if any(
            text in " ".join(longer) and longer_count >= 0.85 * count
            for longer, longer_count in kept
        ):
            continue
        kept.append((gram, count))
    kept.sort(key=lambda item: -item[1])
    return {
        "phrases": [
            {
                "phrase": " ".join(gram),
                "sessions": count,
                "months": sorted(months[gram]),
            }
            for gram, count in kept[:limit]
        ],
        "short_prompts": [
            {"prompt": text, "sessions": len(ids)}
            for text, ids in sorted(short.items(), key=lambda item: -len(item[1]))[
                :limit
            ]
            if len(ids) >= min_sessions
        ],
    }


def phrases_markdown(report: dict[str, Any]) -> str:
    text = "# Repeated phrases\n\nPhrases typed in many separate sessions.\n\n"
    text += markdown_table(
        ("sessions", "phrase", "first", "last"),
        (
            (p["sessions"], p["phrase"], p["months"][0], p["months"][-1])
            for p in report["phrases"]
        ),
    )
    text += "\n## Repeated short prompts\n\n"
    text += markdown_table(
        ("sessions", "prompt"),
        ((p["sessions"], p["prompt"]) for p in report["short_prompts"]),
    )
    return text


